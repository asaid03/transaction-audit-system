import unittest

import pandas as pd

from transaction_audit.bundle_workflow import maybe_clean_transactions, run_bundle_audit
from transaction_audit.datasets import AuditBundle, AuditDataset, DatasetType


class BundleWorkflowTests(unittest.TestCase):
    def test_run_bundle_audit_combines_transaction_and_reference_issues(self):
        transactions = AuditDataset(
            dataset_type=DatasetType.TRANSACTIONS,
            dataframe=pd.DataFrame(
                {
                    "transaction_id": ["TXN-001"],
                    "transaction_date": ["2026-05-01"],
                    "account_id": ["OPS"],
                    "amount": ["0"],
                    "currency": ["USD"],
                    "counterparty": ["Unknown Vendor"],
                    "vendor_id": ["VEN-404"],
                }
            ),
            source_name="transactions.csv",
        )
        vendors = AuditDataset(
            dataset_type=DatasetType.VENDORS,
            dataframe=pd.DataFrame({"vendor_id": ["VEN-001"], "vendor_name": ["Known Vendor"]}),
            source_name="vendors.csv",
        )

        result = run_bundle_audit(AuditBundle(transactions=transactions, vendors=vendors))
        issue_types = result.all_issues_dataframe()["issue_type"].tolist()

        self.assertIn("zero_amount", issue_types)
        self.assertIn("unknown_vendor_reference", issue_types)

    def test_maybe_clean_transactions_leaves_clean_canonical_file_alone(self):
        raw = pd.DataFrame(
            {
                "transaction_id": ["TXN-001"],
                "transaction_date": ["2026-05-01"],
                "account_id": ["OPS"],
                "amount": ["100.00"],
                "currency": ["USD"],
                "counterparty": ["Known Vendor"],
            }
        )

        prepared, cleaning_result = maybe_clean_transactions(raw)

        self.assertIsNone(cleaning_result)
        pd.testing.assert_frame_equal(raw, prepared)

    def test_maybe_clean_transactions_keeps_table_like_export_columns(self):
        raw = pd.DataFrame(
            {
                "transaction_id": ["TXN-001"],
                "date": ["2026-05-01"],
                "vendor_id": ["VEN-001"],
                "account_code": ["5100"],
                "amount": ["100.00"],
                "currency": ["USD"],
                "description": ["Software payment"],
            }
        )

        prepared, cleaning_result = maybe_clean_transactions(raw)

        self.assertIsNone(cleaning_result)
        self.assertEqual(list(raw.columns), list(prepared.columns))
        pd.testing.assert_frame_equal(raw, prepared)

    def test_maybe_clean_transactions_drops_footers_even_when_schema_is_ready(self):
        raw = pd.DataFrame(
            {
                "transaction_id": ["TXN-001", "Total Debits", "Generated by bank"],
                "transaction_date": ["2026-05-01", "", ""],
                "account_id": ["OPS", "", ""],
                "amount": ["100.00", "100.00", ""],
                "currency": ["USD", "", ""],
                "counterparty": ["Known Vendor", "", ""],
            }
        )

        prepared, cleaning_result = maybe_clean_transactions(raw)

        self.assertIsNotNone(cleaning_result)
        self.assertEqual(1, len(prepared))
        self.assertEqual("TXN-001", prepared.loc[0, "transaction_id"])
